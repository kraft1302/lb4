// Процедура TrianglePS
// a - вхідний параметр (передається за значенням)
// P, S - вихідні параметри (передаються за посиланням за допомогою &)
void TrianglePS(double a, double &P, double &S) {
    P = 3 * a;
    S = (a * a * std::sqrt(3)) / 4;
}

