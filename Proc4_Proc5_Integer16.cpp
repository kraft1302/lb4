// Процедура RectPS
// x1, y1, x2, y2 - вхідні параметри
// P, S - вихідні параметри (передаються за посиланням за допомогою &)
void RectPS(double x1, double y1, double x2, double y2, double &P, double &S) {
    // Обчислюємо довжину і ширину прямокутника як абсолютну різницю координат
    double width = std::abs(x1 - x2);
    double height = std::abs(y1 - y2);

    // Обчислюємо периметр і площу
    P = 2 * (width + height);
    S = width * height;
}

